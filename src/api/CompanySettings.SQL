create table public."CompanySettings" (
  id bigint generated by default as identity primary key,
  "companyName" text,
  "taxId" text,
  website text,
  headquarters text,
  "adminEmail" text,
  "supportPhone" text,
  "logoUrl" text,
  "emailNotifications" boolean default true,
  "slackIntegration" boolean default false,
  "realtimePush" boolean default true
);

alter table public."CompanySettings" enable row level security;
create policy "authenticated all" on public."CompanySettings"
  for all to authenticated using (true) with check (true);